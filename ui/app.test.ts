import { afterEach, describe, expect, it, vi } from 'vitest';
import { fireEvent, screen, waitFor } from '@testing-library/dom';
import userEvent from '@testing-library/user-event';
import { createApp } from './app';
import { fixture } from './test/fixture';
import type { Invoke, Snapshot } from './types';
let app: ReturnType<typeof createApp>;
const total = new Intl.NumberFormat().format(12840);
function setup(overrides: Partial<Snapshot> = {}, handler?: (cmd: string, args?: Record<string, unknown>) => unknown) {
  const state = { ...structuredClone(fixture), ...overrides };
  document.body.innerHTML = '<div id="app"></div>';
  const invoke = vi.fn(async (cmd: string, args?: Record<string, unknown>) => {
    if (cmd === 'snapshot') return structuredClone(state);
    if (handler) return handler(cmd, args);
    if (cmd === 'failure_page') return { rows: [], next: null };
    return undefined;
  });
  app = createApp(document.querySelector('#app')!, invoke as Invoke, 60000);
  return { invoke, state };
}
afterEach(() => app?.dispose());
describe('desktop flows', () => {
  it('shows startup as preparation rather than an empty or broken catalogue, and keeps Close available', async () => {
    const { invoke } = setup({ storage_ok:false,storage_checking:true,catalogue_loaded:false,busy:true,detail:'Opening catalogue…' });
    await screen.findByText('Loading saved catalogue…');
    expect(document.querySelector('#lifetime')?.textContent).toBe('—');
    expect(screen.queryByText('Storage needs attention')).toBeNull();
    expect(screen.getByText('Opening local storage')).toBeTruthy();
    expect((screen.getByRole('button',{name:/Start crawl/}) as HTMLButtonElement).disabled).toBe(true);
    expect((screen.getByRole('button',{name:'Stop'}) as HTMLButtonElement).disabled).toBe(true);
    await userEvent.click(screen.getByRole('button',{name:/Close application/}));
    expect(invoke).toHaveBeenCalledWith('quit');
  });
  it('opens a dismissible main-menu flyout containing all eight workspaces and manages focus', async () => {
    const { invoke } = setup();
    await screen.findByText(total);
    const user = userEvent.setup();
    const toggle = screen.getByRole('button', { name: 'Open main menu' });
    const frame = document.querySelector<HTMLElement>('.app-frame')!;
    expect(screen.queryByRole('dialog')).toBeNull();
    expect(toggle.getAttribute('aria-expanded')).toBe('false');
    await user.click(toggle);
    const menu = screen.getByRole('dialog', { name: 'Main menu' });
    const close = screen.getByRole('button', { name: 'Close main menu' });
    const crawlers = screen.getByRole('button', { name: /Crawlers/ });
    expect(menu.querySelectorAll('nav button')).toHaveLength(8);
    expect([...menu.querySelectorAll('nav button')].map(b => b.id)).toEqual(['menu-crawlers', 'menu-discovery', 'menu-dnd', 'menu-osr', 'menu-shadowrun', 'menu-coc', 'menu-warhammer_fantasy', 'menu-warhammer_40k']);
    expect(crawlers.getAttribute('aria-current')).toBe('page');
    expect(toggle.getAttribute('aria-expanded')).toBe('true');
    expect(frame.inert).toBe(true);
    expect(document.activeElement).toBe(close);
    await user.tab({ shift: true });
    expect(document.activeElement).toBe(screen.getByRole('button', { name: /Warhammer 40k/ }));
    await user.tab();
    expect(document.activeElement).toBe(close);
    await user.keyboard('{Escape}');
    expect(screen.queryByRole('dialog')).toBeNull();
    expect(frame.inert).toBe(false);
    expect(document.activeElement).toBe(toggle);
    await user.click(toggle);
    await user.click(document.querySelector('#menu-backdrop')!);
    expect(document.activeElement).toBe(toggle);
    expect(screen.queryByRole('dialog')).toBeNull();
    await user.click(toggle);
    await user.click(close);
    expect(toggle.getAttribute('aria-expanded')).toBe('false');
    expect(document.querySelector('#analysis-workspace')).toBeNull();
    expect(document.querySelector('[id*=search]')).toBeNull();
    expect(invoke.mock.calls.map(c => c[0])).toEqual(['snapshot']);
  });
  it('moves the five crawler views into keyboard-accessible tabs, including during startup', async () => {
    const { invoke } = setup({ storage_ok: false, storage_checking: true, catalogue_loaded: false, busy: true });
    await screen.findByText('Opening local storage');
    const tabs = screen.getAllByRole('tab');
    expect(tabs.map(t => t.textContent?.slice(1))).toEqual(['Overview', 'Authentication', 'Unsuccessful jobs', 'Local storage', 'About']);
    const [overview, auth, , , about] = tabs;
    fireEvent.keyDown(overview, { key: 'ArrowRight' });
    expect(auth.getAttribute('aria-selected')).toBe('true');
    expect(document.activeElement).toBe(auth);
    expect(screen.getByRole('tabpanel', { name: 'Authentication' })).toBeTruthy();
    fireEvent.keyDown(auth, { key: 'ArrowLeft' });
    expect(document.activeElement).toBe(overview);
    fireEvent.keyDown(overview, { key: 'ArrowLeft' });
    expect(document.activeElement).toBe(about);
    expect((screen.getByRole('button', { name: 'Reprocess saved responses' }) as HTMLButtonElement).disabled).toBe(true);
    fireEvent.keyDown(about, { key: 'ArrowRight' });
    expect(document.activeElement).toBe(overview);
    fireEvent.keyDown(overview, { key: 'End' });
    expect(document.activeElement).toBe(about);
    fireEvent.keyDown(about, { key: 'Home' });
    expect(document.activeElement).toBe(overview);
    expect(tabs.filter(t => t.tabIndex === 0)).toEqual([overview]);
    expect(screen.getByRole('tabpanel', { name: 'Overview' })).toBeTruthy();
    expect(invoke.mock.calls.map(c => c[0])).toEqual(['snapshot']);
    await userEvent.click(screen.getByRole('button', { name: /Close application/ }));
    expect(invoke).toHaveBeenCalledWith('quit');
  });
  it('retains the selected crawler tab and masked authentication draft when selecting Crawlers', async () => {
    const { invoke } = setup();
    await screen.findByText(total);
    const user = userEvent.setup();
    const auth = screen.getByRole('tab', { name: 'Authentication' });
    await user.click(auth);
    await user.click(screen.getByRole('radio', { name: /Paste cookie headers/ }));
    await user.click(screen.getByRole('button', { name: /Continue/ }));
    const website = screen.getByLabelText(/Website ·/) as HTMLInputElement;
    await user.type(website, 'synthetic=DRAFT_FIXTURE');
    await user.click(screen.getByRole('button', { name: 'Open main menu' }));
    await user.click(screen.getByRole('button', { name: /Crawlers/ }));
    expect(screen.queryByRole('dialog')).toBeNull();
    expect(document.activeElement).toBe(auth);
    expect(auth.getAttribute('aria-selected')).toBe('true');
    expect(screen.getByLabelText(/Website ·/)).toBe(website);
    expect(website.value).toBe('synthetic=DRAFT_FIXTURE');
    expect(website.type).toBe('password');
    await user.click(auth);
    expect(screen.getByLabelText(/Website ·/)).toBe(website);
    expect(invoke.mock.calls.some(c => ['save_auth', 'test_access', 'start'].includes(c[0]))).toBe(false);
  });
  it('loads existing totals without starting a crawl and gates Start on storage and selection', async () => {
    const { invoke } = setup({ storage_ok: false });
    await screen.findByText(total);
    expect((screen.getByRole('button', { name: /Start crawl/ }) as HTMLButtonElement).disabled).toBe(true);
    expect(invoke.mock.calls.map(c => c[0])).toEqual(['snapshot']);
    await userEvent.click(screen.getByRole('tab', { name: /Local storage/ }));
    expect(screen.queryByText('SAVED THIS RUN')).toBeNull();
    expect(screen.getByText(/same files as the terminal app/)).toBeTruthy();
  });
  it('retains wizard answers on Back, masks review, and keeps failed Test Access isolated', async () => {
    const { invoke } = setup({ auth_method: 'anonymous' }, (cmd) => cmd === 'test_access' ? { passed: false, text: 'Synthetic policy failure' } : undefined);
    await screen.findByText(total);
    const user = userEvent.setup();
    await user.click(screen.getByRole('tab', { name: /Authentication/ }));
    await user.click(screen.getByRole('radio', { name: /Paste cookie headers/ }));
    await user.click(screen.getByRole('button', { name: /Continue/ }));
    const website = screen.getByLabelText(/Website ·/) as HTMLInputElement;
    const api = screen.getByLabelText(/API ·/) as HTMLInputElement;
    await user.type(website, 'synthetic=PRIVATE_FIXTURE');
    await user.type(api, 'synthetic=OTHER_FIXTURE');
    expect(website.type).toBe('password');
    await user.click(screen.getByRole('button', { name: /Continue/ }));
    await user.click(screen.getByRole('button', { name: /Back/ }));
    expect((screen.getByLabelText(/Website ·/) as HTMLInputElement).value).toContain('PRIVATE_FIXTURE');
    await user.click(screen.getByRole('button', { name: /Continue/ }));
    await user.click(screen.getByRole('button', { name: /Continue/ }));
    expect(document.body.textContent).not.toContain('PRIVATE_FIXTURE');
    await user.click(screen.getByRole('button', { name: /Save & test access/ }));
    await screen.findByText('Synthetic policy failure');
    expect(screen.queryByText('SAVED THIS RUN')).toBeNull();
    expect(screen.getByRole('tab', { name: 'Authentication' }).getAttribute('aria-selected')).toBe('true');
    expect(invoke.mock.calls.some(c => c[0] === 'start')).toBe(false);
    await user.click(screen.getByRole('button', { name: /Back to authentication/ }));
    expect(screen.getByText('Keep currently loaded headers')).toBeTruthy();
  });
  it('does not expose remote text as HTML and uses keyset failure pages', async () => {
    const { invoke } = setup({}, (cmd, args) => cmd === 'failure_page' ? { rows: [args?.after ? 'Second page' : '<img src=x onerror=alert(1)>'], next: args?.after ? null : 100 } : undefined);
    await screen.findByText(total);
    await userEvent.click(screen.getByRole('tab', { name: /Unsuccessful jobs/ }));
    await screen.findByText('<img src=x onerror=alert(1)>');
    expect(document.querySelector('img')).toBeNull();
    await userEvent.click(screen.getByRole('button', { name: 'Next 100' }));
    await screen.findByText('Second page');
    expect(invoke).toHaveBeenCalledWith('failure_page', { after: 100 });
  });
  it('keeps Stop reachable while another operation is pending', async () => {
    const { invoke } = setup({ active: true, busy: true, state: 'crawling' });
    await screen.findByText(total);
    await userEvent.click(screen.getByRole('tab', { name: 'Local storage' }));
    expect(document.querySelector('#crawler-state')?.textContent).toBe('crawling');
    await userEvent.click(screen.getByRole('button', { name: 'Open main menu' }));
    await userEvent.click(screen.getByRole('button', { name: /Crawlers/ }));
    await userEvent.click(screen.getByRole('tab', { name: 'Overview' }));
    expect(invoke.mock.calls.map(c => c[0])).toEqual(['snapshot']);
    const stop = screen.getByRole('button', { name: 'Stop' }) as HTMLButtonElement;
    expect(stop.disabled).toBe(false);
    fireEvent.click(stop);
    await waitFor(() => expect(invoke).toHaveBeenCalledWith('stop'));
  });
  it('opens Discovery with one Analysis tab, preserves crawler drafts and gates crawling during the sequence', async () => {
    const { invoke, state } = setup({}, command => {
      if (command === 'analysis_overview') return { catalogue_total: 0, analyses: {} };
      if (command === 'start_discovery_analysis') state.analysis = { ...state.analysis, state: 'running', discovery: { step: 0, completed_steps: 0, rerun_all: false, unsuccessful: 0 } };
    });
    await screen.findByText(total);
    const user = userEvent.setup();
    await user.click(screen.getByRole('tab', { name: 'Authentication' }));
    await user.click(screen.getByRole('radio', { name: /Paste cookie headers/ }));
    await user.click(screen.getByRole('button', { name: /Continue/ }));
    await user.type(screen.getByLabelText(/Website ·/), 'synthetic=DRAFT_FIXTURE');
    await user.click(screen.getByRole('button', { name: 'Open main menu' }));
    await user.click(screen.getByRole('button', { name: /Discovery/ }));
    expect(screen.getAllByRole('tab')).toHaveLength(1);
    expect(document.activeElement).toBe(screen.getByRole('tab', { name: 'Analysis' }));
    expect(screen.getByRole('tabpanel', { name: 'Analysis' })).toBeTruthy();
    expect(screen.queryByRole('combobox')).toBeNull();
    expect(invoke.mock.calls.some(c => c[0].startsWith('start_'))).toBe(false);
    await user.click(screen.getByRole('button', { name: 'Run analyses' }));
    await screen.findByRole('button', { name: 'Cancel analysis' });
    await user.click(screen.getByRole('button', { name: 'Open main menu' }));
    expect(screen.getByRole('button', { name: /Discovery/ }).getAttribute('aria-current')).toBe('page');
    await user.click(screen.getByRole('button', { name: /Crawlers/ }));
    expect((screen.getByLabelText(/Website ·/) as HTMLInputElement).value).toBe('synthetic=DRAFT_FIXTURE');
    await user.click(screen.getByRole('tab', { name: 'Overview' }));
    expect((screen.getByRole('button', { name: /Start crawl/ }) as HTMLButtonElement).disabled).toBe(true);
    expect(invoke.mock.calls.filter(c => c[0] === 'start_discovery_analysis')).toHaveLength(1);
    expect(invoke.mock.calls.some(c => ['start', 'stop', 'save_auth', 'cancel_analysis'].includes(c[0]))).toBe(false);
  });
});
